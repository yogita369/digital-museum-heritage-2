// Shared helpers for reading the project's .env file (credentials for YOUR
// Cloudflare and HCP Terraform accounts). Used by doctor.mjs and
// seed-sample-data.mjs. For terraform commands, use scripts/load-env.sh / .ps1.
//
// Values are never printed by these scripts.

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const ENV_FILE = join(ROOT, ".env");
export const ENV_EXAMPLE = join(ROOT, ".env.example");

// Every setting the project needs, in the order they are usually obtained.
export const SETTINGS = {
  CLOUDFLARE_API_TOKEN: "Cloudflare API token (Workers Scripts: Edit, Workers KV Storage: Edit)",
  CLOUDFLARE_ACCOUNT_ID: "Cloudflare account ID (32 hexadecimal characters)",
  WORKERS_SUBDOMAIN: "workers.dev subdomain (the <name> in <name>.workers.dev)",
  TF_CLOUD_ORGANIZATION: "HCP Terraform organization name",
  TF_API_TOKEN: "HCP Terraform API token",
  CURATOR_API_KEY: "Curator key for the app (generated by doctor.mjs --init-env)",
};

export function parseEnvFile(path = ENV_FILE) {
  if (!existsSync(path)) return null;
  const values = {};
  for (const raw of readFileSync(path, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim().replace(/^export\s+/, "");
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

// Settings from .env, with already-exported environment variables taking priority.
export function loadSettings() {
  const file = parseEnvFile() || {};
  const settings = {};
  for (const key of Object.keys(SETTINGS)) {
    settings[key] = (process.env[key] || file[key] || "").trim();
  }
  return settings;
}

export function missingSettings(settings, keys = Object.keys(SETTINGS)) {
  return keys.filter((key) => !settings[key]);
}

// Environment for running Terraform: maps the .env names to the names
// Terraform reads (TF_VAR_* input variables and the HCP credentials variable).
export function terraformEnv(settings) {
  const env = { ...process.env };
  const set = (name, value) => {
    if (value) env[name] = value;
  };
  set("CLOUDFLARE_API_TOKEN", settings.CLOUDFLARE_API_TOKEN);
  set("TF_CLOUD_ORGANIZATION", settings.TF_CLOUD_ORGANIZATION);
  set("TF_TOKEN_app_terraform_io", settings.TF_API_TOKEN);
  set("TF_VAR_account_id", settings.CLOUDFLARE_ACCOUNT_ID);
  set("TF_VAR_workers_subdomain", settings.WORKERS_SUBDOMAIN);
  set("TF_VAR_curator_api_key", settings.CURATOR_API_KEY);
  return env;
}

export function failMissing(missing) {
  console.error(`Missing in .env: ${missing.join(", ")}`);
  console.error("Fill them in (see .env.example), then run: npm run doctor");
  process.exit(1);
}
